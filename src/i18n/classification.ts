export function classificationLabel(locale: Locale, label: string): string {
  if (locale === "en") return label;
  return ES_LABELS[label] ?? Object.entries(ES_LABELS).find(([key]) => key.toLocaleLowerCase("en-US") === label.trim().toLocaleLowerCase("en-US"))?.[1] ?? label;
}

export function marketDetailLabel(locale: Locale, label: string): string {
  if (locale === "en") return label;
  const priceReturn = label.match(/^(.*?)\s*·\s*price return$/i);
  if (priceReturn) return `${priceReturn[1]} · rendimiento del precio`;
  return classificationLabel(locale, label);
}
