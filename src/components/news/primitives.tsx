/**
 * Primitivas visuales de la capa de inteligencia. Regla: el usuario nunca debe confundir un HECHO con
 * una INFERENCIA del sistema. Cada afirmación lleva su tipo:
 *   SOURCE BASED (medios) · OFFICIAL (fuente primaria) · REAL (datos de MarketRadar) · INFERRED · AI · UNKNOWN
 */
const CLAIM: Record<ClaimKind, { label: string; variant: "official" | "neutral" | "positive" | "inferred" | "ai" | "outline"; title: string }> = {
  FACT: { label: "Official", variant: "official", title: "Fact from an official primary source (SEC EDGAR, central bank, statistics agency)" },
  SOURCE_CLAIM: { label: "Source based", variant: "neutral", title: "What a media source reports — attributed, may be incomplete or wrong" },
  MARKET_DATA: { label: "Real data", variant: "positive", title: "Calculated by MarketRadar from its real data (Alpaca prices, SEC fundamentals, synthetic indices)" },
  INFERENCE: { label: "Inferred", variant: "inferred", title: "Relationship inferred by MarketRadar's rules and curated graph — not a reported fact" },
  AI_INTERPRETATION: { label: "AI", variant: "ai", title: "Interpretation generated by an AI model, validated against the cited evidence" },
  UNKNOWN: { label: "Unknown", variant: "outline", title: "Not enough evidence — MarketRadar does not guess" },
};

export function ClaimKindBadge({ kind }: { kind: ClaimKind }) {
  const { locale } = useI18n();
  const labels: Record<ClaimKind, { label: string; title: string }> = locale === "es" ? {
    FACT: { label: "Oficial", title: "Hecho de una fuente primaria oficial (SEC EDGAR, banco central u organismo estadístico)" },
    SOURCE_CLAIM: { label: "Según fuentes", title: "Información publicada por un medio; se atribuye y puede ser incompleta o incorrecta" },
    MARKET_DATA: { label: "Datos reales", title: "Calculado por MarketRadar a partir de sus datos reales (precios Alpaca, fundamentales SEC e índices sintéticos)" },
    INFERENCE: { label: "Inferido", title: "Relación inferida por las reglas y el grafo de MarketRadar; no es un hecho publicado" },
    AI_INTERPRETATION: { label: "IA", title: "Interpretación generada por un modelo de IA y contrastada con la evidencia citada" },
    UNKNOWN: { label: "Desconocido", title: "Evidencia insuficiente; MarketRadar no hace conjeturas" },
  } : Object.fromEntries(Object.entries(CLAIM).map(([key, value]) => [key, { label: value.label, title: value.title }])) as Record<ClaimKind, { label: string; title: string }>;
  const c = { ...CLAIM[kind], ...labels[kind] };
  return (
    <Badge variant={c.variant} title={c.title}>
      {c.label}
    </Badge>
  );
}

const CONF_LABEL = (score: number) => (score >= 0.72 ? "High" : score >= 0.5 ? "Medium" : "Low");

export function confidenceTitle(c: ConfidenceBreakdown, locale: "es" | "en" = "en"): string {
  if (locale === "es") return [
    `Confianza ${Math.round(c.score * 100)}/100 (${c.score >= 0.72 ? "Alta" : c.score >= 0.5 ? "Media" : "Baja"}) — cuánto confiamos en que el evento ocurrió como se describe y en que las entidades son correctas. No predice precios.`,
    `Calidad de fuente ${Math.round(c.sourceQuality * 100)} · Corroboración ${Math.round(c.corroboration * 100)} · Coincidencia de entidad ${Math.round(c.entityMatch * 100)} · Recencia ${Math.round(c.recency * 100)} · Clasificación ${Math.round(c.classification * 100)} · Acuerdo ${Math.round(c.agreement * 100)} · Certeza ${Math.round((c.eventCertainty ?? 0) * 100)}`,
    ...c.notes,
  ].join("\n");
  return [
    `Confidence ${Math.round(c.score * 100)}/100 (${CONF_LABEL(c.score)}) — how much we trust that the event happened as described and entities are right. Not a price prediction.`,
    `Source quality ${Math.round(c.sourceQuality * 100)} · Corroboration ${Math.round(c.corroboration * 100)} · Entity match ${Math.round(c.entityMatch * 100)} · Recency ${Math.round(c.recency * 100)} · Classification ${Math.round(c.classification * 100)} · Agreement ${Math.round(c.agreement * 100)} · Certainty ${Math.round((c.eventCertainty ?? 0) * 100)}`,
    ...c.notes,
  ].join("\n");
}

export function ConfidenceMeter({ confidence, className }: { confidence: ConfidenceBreakdown; className?: string }) {
  const { locale } = useI18n();
  const pct = Math.round(confidence.score * 100);
  const label = locale === "es" ? (confidence.score >= 0.72 ? "Alta" : confidence.score >= 0.5 ? "Media" : "Baja") : CONF_LABEL(confidence.score);
  return (
    <span className={cn("inline-flex items-center gap-1.5 text-[10px] text-fg-muted", className)} title={confidenceTitle(confidence, locale)}>
      <span role="meter" aria-valuemin={0} aria-valuemax={100} aria-valuenow={pct} aria-label={`${locale === "es" ? "Confianza" : "Confidence"} ${pct} ${locale === "es" ? "de" : "of"} 100`} className="relative h-1 w-10 overflow-hidden rounded-full bg-surface-hover">
        <span className={cn("absolute inset-y-0 left-0 rounded-full", label === "High" ? "bg-fg-secondary" : label === "Medium" ? "bg-fg-muted" : "bg-warning")} style={{ width: `${pct}%` }} />
      </span>
      <span className="font-mono">{pct}</span>
      <span className="uppercase">{label}</span>
    </span>
  );
}

const DIR: Record<ImpactDirection, { symbol: string; cls: string }> = {
  potential_positive: { symbol: "↗", cls: "text-positive" },
  potential_negative: { symbol: "↘", cls: "text-negative" },
  mixed_uncertain: { symbol: "↔", cls: "text-fg-secondary" },
};

export function DirectionMark({ direction, label }: { direction: ImpactDirection; label?: string }) {
  const { locale } = useI18n();
  const d = DIR[direction];
  const translated = enumLabel(locale, direction) || label || "";
  return (
    <span className={cn("inline-flex items-center gap-1 whitespace-nowrap", d.cls)} title={`${translated} — ${locale === "es" ? "relación potencial, no una predicción" : "potential relationship, not a prediction"}`}>
      <span aria-hidden>{d.symbol}</span>
      <span className="text-[10px] font-semibold uppercase">{translated.replace(/^Potential /, "")}</span>
    </span>
  );
}

