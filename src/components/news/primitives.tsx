/** Chip de entidad: DIRECT (mencionada) con borde sólido; INFERRED con borde discontinuo y color de inferencia. */
export function EntityChip({ chip, short }: { chip: NodeChip; short?: string }) {
  const { locale } = useI18n();
  const inferred = chip.relation === "INFERRED";
  const label = classificationLabel(locale, chip.label);
  const method = locale === "es" ? ({ alias: "alias", alias_context: "alias contextual", cik: "código CIK", keyword: "palabra clave", classification: "clasificación", macro_scope: "ámbito macro", event_rule: "regla de evento" } as Record<string, string>)[chip.method] ?? chip.method : chip.method;
  const evidence = locale !== "es" ? chip.evidence : (() => {
    if (chip.method === "classification") {
      const match = chip.evidence.match(/^(.*?) is classified in GICS (.+)$/);
      if (match) return `${match[1]} tiene la clasificación GICS ${classificationLabel(locale, match[2] ?? "")}`;
    }
    if (chip.method === "macro_scope") {
      const generated: Record<string, string> = {
        "Central bank events can affect the overall market": "Los eventos de bancos centrales pueden afectar al mercado en general",
        "Growth & activity events can affect the overall market": "Los eventos de crecimiento y actividad pueden afectar al mercado en general",
        "Rates & bonds events can affect the overall market": "Los eventos de tipos y bonos pueden afectar al mercado en general",
        "Trade & tariffs events can affect the overall market": "Los eventos de comercio y aranceles pueden afectar al mercado en general",
        "Growth & activity events relate to Economic growth": "Los eventos de crecimiento y actividad están relacionados con el crecimiento económico",
        "AI & data centers events relate to AI demand": "Los eventos de IA y centros de datos están relacionados con la demanda de IA",
      };
      if (generated[chip.evidence]) return generated[chip.evidence];
    }
    return chip.evidence.replace(/ · in (\d+)\/(\d+) articles/g, " · en $1/$2 artículos");
  })();
  const title = `${label} — ${inferred ? (locale === "es" ? "INFERIDO" : "INFERRED") : (locale === "es" ? "MENCIÓN DIRECTA" : "DIRECT MENTION")} (${method}, ${locale === "es" ? "confianza" : "confidence"} ${Math.round(chip.confidence * 100)}): ${evidence}`;
  const cls = cn(
    "inline-flex max-w-44 items-center gap-1 truncate rounded-[3px] border px-1.5 py-px text-[10px] leading-4",
    inferred ? "border-dashed border-inferred/50 text-inferred" : "border-border-strong text-fg-secondary",
    chip.href && "hover:border-accent hover:text-accent",
  );
  const content = (
    <>
      {inferred && <span aria-hidden className="text-[9px]">≈</span>}
      <span className={cn(chip.kind === "company" && "font-mono")}>{short ?? label}</span>
    </>
  );
  return chip.href ? (
    <Link href={chip.href} className={cls} title={title}>
      {content}
    </Link>
  ) : (
    <span className={cls} title={title}>
      {content}
    </span>
  );
}

const STATUS: Record<NewsEvent["status"], { label: string; variant: "accent" | "neutral" | "outline" }> = {
  developing: { label: "Developing", variant: "accent" },
  active: { label: "Active", variant: "neutral" },
  stale: { label: "Older", variant: "outline" },
};

export function StatusBadge({ status }: { status: NewsEvent["status"] }) {
  const { locale } = useI18n();
  const s = STATUS[status];
  const label = locale === "es" ? ({ developing: "En desarrollo", active: "Activo", stale: "Anterior" } as const)[status] : s.label;
  const title = locale === "es" ? "En desarrollo: detectado hace menos de 6 h · Activo: artículos nuevos en las últimas 48 h · Anterior: sin cobertura nueva durante 48 h" : "Developing: first seen < 6 h ago · Active: new articles in the last 48 h · Older: no new coverage for 48 h";
  return (
    <Badge variant={s.variant} title={title}>
      {label}
    </Badge>
  );
}

export function timeAgo(iso: string, now: Date = new Date()): string {
  const diff = Math.max(0, now.getTime() - Date.parse(iso));
  const m = Math.round(diff / 60_000);
  if (m < 60) return `${Math.max(1, m)}m ago`;
  const h = Math.round(m / 60);
  if (h < 48) return `${h}h ago`;
  return `${Math.round(h / 24)}d ago`;
}

export function TimeAgo({ iso, now }: { iso: string; now?: Date }) {
  const { locale } = useI18n();
  return (
    <time dateTime={iso} title={new Date(iso).toUTCString()} className="whitespace-nowrap">
      {formatRelativeTime(iso, now, locale)}
    </time>
  );
}

